export const NEXT_LEVEL_MISSIONS: Mission[] = tracks.flatMap(({ track, offset, rows }) =>
  rows.map(([title, detail, files, steps, acceptance, dependencies, external], index) => {
    const n = offset + index + 1;
    return {
      id: "next-" + String(n).padStart(3, "0"),
      title,
      detail,
      done: (NEXT_LEVEL_COMPLETED_IDS as readonly string[]).includes("next-" + String(n).padStart(3,"0")),
      status: (NEXT_LEVEL_COMPLETED_IDS as readonly string[]).includes("next-" + String(n).padStart(3,"0")) ? "complete" : "planned",
      brief: {
        track,
        priority: critical.has(n) ? "P0" : n <= 60 ? "P1" : "P2",
        dependsOn: dependencies.map((d) => "next-" + String(d).padStart(3, "0")),
        files: files.split("|"),
        steps: steps.split("|"),
        acceptance: acceptance.split("|"),
        ...(external ? { external } : {}),
      },
    };
  }),
);
export const NEXT_LEVEL_TRACKS = tracks.map((t) => t.track);
export function formatMissionBrief(
  mission: Mission,
  context: readonly Mission[] = NEXT_LEVEL_MISSIONS,
): string {
  const brief = mission.brief;
  const dependencies =
    brief?.dependsOn.map((id) => {
      const dependency = context.find((m) => m.id === id);
      return (
        "- " +
        id +
        (dependency
          ? " — " +
            dependency.title +
            " [" +
            (dependency.done ? "complete" : (dependency.status ?? "planned")) +
            "]"
          : " — resolve this prerequisite")
      );
    }) ?? [];
  return [
    "# " + mission.id + " — " + mission.title,
    "Status: " + (mission.done ? "complete" : (mission.status ?? "planned")),
    ...(brief ? ["Track: " + brief.track, "Priority: " + brief.priority] : []),
    "\n## Problem and intended outcome",
    mission.detail,
    "\n## Execution contract",
    ...MODEL_EXECUTION_RULES.map((rule, i) => i + 1 + ". " + rule),
    "\n## Dependencies",
    ...(dependencies.length ? dependencies : ["None."]),
    "\n## Start in",
    ...(brief?.files.map((f) => "- " + f) ?? [
      "Inspect the existing implementation and its tests.",
    ]),
    "\n## Implementation",
    ...(brief?.steps.map((s, i) => i + 1 + ". " + s) ?? [
      "Implement the intended outcome and preserve current saved behavior.",
    ]),
    "\n## Acceptance checks",
    ...(brief?.acceptance.map((a) => "- [ ] " + a) ?? [
      "- [ ] Demonstrate the requested behavior, failure recovery and relevant validation.",
    ]),
    ...(brief?.external
      ? [
          "\n## External requirement",
          brief.external,
          "Do not claim this external requirement passed from fixtures alone.",
        ]
      : []),
    "\n## Required handoff",
    "Changed files; baseline/reproduction; validation commands and results; artifact paths; remaining external checks; resulting milestone status.",
  ].join("\n");
}
export function formatNextLevelRoadmap(missions: readonly Mission[] = NEXT_LEVEL_MISSIONS): string {
  return (
    [
      "# Realhub — 100 next-level milestones",
      "All 100 additions start planned. Existing completion decisions are retained. P0 denotes foundational correctness/reliability risk; P1 denotes core workflow quality; P2 denotes capability and polish. Dependencies take precedence over priority.",
      "This file is generated from verified defaults. Use the current in-app status when executing; later manual status decisions remain local.",
      ...missions.map((m) => formatMissionBrief(m, missions)),
    ].join("\n\n---\n\n") + "\n"
  );
}
