import { registerHooks } from 'node:module';
import { performance } from 'node:perf_hooks';
import assert from 'node:assert/strict';
registerHooks({ resolve(s, c, n) { try { return n(s, c); } catch (e) { if (s.startsWith('.') && !/\.[a-z]+$/i.test(s)) return n(s + '.ts', c); throw e; } } });
const { createCatalogCounter } = await import('../src/lib/videos/catalog-count-cache.ts');
const { lookupVideo } = await import('../src/lib/videos/video-lookup.ts');
// Model browser task scheduling without Windows timer-clamp noise.
globalThis.scheduler = { postTask: fn => new Promise(resolve => setImmediate(() => resolve(fn()))) };
const entries = Number(process.argv[2] ?? 1_000_000);
let metadataReads = 0;
const remote = { kind: 'youtube' };
const videos = Array.from({ length: entries }, (_, i) => ({ id: `yt:${i}`, folderId: 'yt:creator', get remote() { metadataReads++; return remote; } }));
const counter = createCatalogCounter(), policy = { adultIds: new Set(), hidden: {}, hideDemo: false };
let turns = 0;
const turn = () => { turns++; return globalThis.scheduler.postTask(() => {}); };
const started = performance.now(), counts = await counter.count({ ...policy, videos }, turn);
const coldMs = performance.now() - started;
assert.equal(counts.ytCount, entries); assert(turns > 100);
metadataReads = 0; turns = 0;
const cachedStarted = performance.now();
for (let i = 0; i < 100; i++) assert.equal(await counter.count({ ...policy, videos }, turn), counts);
const cached100Ms = performance.now() - cachedStarted;
assert.equal(metadataReads, 0); assert.equal(turns, 0);
const next = [...videos, { id: 'new', folderId: 'yt:creator', remote }];
const appendStarted = performance.now(), appended = await counter.count({ ...policy, videos: next }, turn);
const appendMs = performance.now() - appendStarted;
assert.equal(appended.ytCount, entries + 1); assert.equal(metadataReads, 0);
let idReads = 0;
const selected = { folderId: 'yt:creator', get id() { idReads++; return 'selected'; } };
const playerCatalog = [...videos, selected];
lookupVideo(playerCatalog, 'selected'); idReads = 0;
const lookupStarted = performance.now();
for (let i = 0; i < 100; i++) assert.equal(lookupVideo([...playerCatalog, { id: `append:${i}` }], 'selected'), selected);
const lookup100MsIncludingArrayCopies = performance.now() - lookupStarted;
assert.equal(idReads, 100);
console.log(JSON.stringify({ entries, coldCounterMs: +coldMs.toFixed(1), cached100CounterUpdatesMs: +cached100Ms.toFixed(2), cachedMetadataReads: 0, cachedTasks: 0, appendCounterMs: +appendMs.toFixed(1), appendMetadataReadsOnUnchangedCards: metadataReads, appendBackgroundTasks: turns, playbackLookups: 100, selectedIdReads: idReads, lookup100MsIncludingArrayCopies: +lookup100MsIncludingArrayCopies.toFixed(1), retainedStrongPreviousCatalogReferences: 0 }, null, 2));
